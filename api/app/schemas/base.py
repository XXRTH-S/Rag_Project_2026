"""คลาสฐานของ payload ที่รับเข้ามาจากภายนอก

pydantic ตั้งต้นด้วยการ **เมินเฉย** field ที่ไม่รู้จัก ซึ่งทำให้ client ที่เดาชื่อ
ผิดได้คำตอบ 2xx พร้อมพฤติกรรมที่ไม่ตรงกับที่ตั้งใจ โดยไม่มีอะไรบอกเลย

เจอจริงในโปรเจกต์นี้: สคริปต์ส่ง {"email":…, "password":…, "is_admin": true}
ไปสร้าง admin แต่ field จริงชื่อ "role" ผลคือได้บัญชี user ธรรมดาเงียบ ๆ
ถ้าปิดช่องนี้ไว้ตั้งแต่แรกจะได้ 422 พร้อมชื่อ field ที่ผิด แก้ได้ในสิบวินาที

ใช้เฉพาะกับสิ่งที่ "รับเข้า" เท่านั้น · โมเดลที่ใช้ "ส่งออก" ไม่ต้องสืบทอดคลาสนี้
เพราะมันแปลงมาจาก ORM ไม่ได้มาจากผู้ใช้
"""
from typing import Generic, TypeVar

from pydantic import BaseModel, ConfigDict


class StrictModel(BaseModel):
    """ปฏิเสธ field ที่ไม่รู้จักด้วย 422 แทนที่จะเมินเฉย"""

    model_config = ConfigDict(extra="forbid")


T = TypeVar("T")


class Page(BaseModel, Generic[T]):
    """ผลลัพธ์แบบแบ่งหน้า

    เดิม list endpoint คืน array เปล่า ๆ พร้อม limit ตายตัวที่ 50 แถว
    ผู้ใช้ที่มีเอกสารมากกว่านั้นจะมองไม่เห็นของเก่า **และไม่มีอะไรบอกว่าถูกตัด**
    ซึ่งแย่กว่าการเห็นไม่ครบ เพราะเข้าใจผิดว่านั่นคือทั้งหมดที่มี

    total ทำให้หน้าเว็บบอกได้ว่า "แสดง 50 จาก 137" และรู้ว่ายังมีให้โหลดอีก
    """

    items: list[T]
    total: int
    limit: int
    offset: int
